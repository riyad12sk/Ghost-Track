import json
from datetime import datetime
from rich.console import Console
from rich.table import Table
from rich.markdown import Markdown
import os

class ReportGenerator:
    def __init__(self, output_dir="output"):
        self.output_dir = output_dir
        self.console = Console()
        # ফোল্ডার না থাকলে স্বয়ংক্রিয়ভাবে তৈরি করার ব্যবস্থা
        os.makedirs(self.output_dir, exist_ok=True)

    def generate_report(self, data, report_type):
        """Generate laporan dalam berbagai format"""
        os.makedirs(self.output_dir, exist_ok=True)
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")

        # Generate JSON
        json_file = f"{self.output_dir}/{report_type}_{timestamp}.json"
        self.save_json(data, json_file)

        # Generate Text Report
        txt_file = f"{self.output_dir}/{report_type}_{timestamp}.txt"
        self.save_text_report(data, txt_file)

        # Generate HTML Report
        html_file = f"{self.output_dir}/{report_type}_{timestamp}.html"
        self.save_html_report(data, html_file)

        return {
            "json": json_file,
            "txt": txt_file,
            "html": html_file
        }

    def save_json(self, data, filename):
        """Simpan data sebagai JSON"""
        with open(filename, 'w', encoding='utf-8') as f:
            json.dump(data, f, indent=4, ensure_ascii=False)

    def save_text_report(self, data, filename):
        """Generate laporan text"""
        with open(filename, 'w', encoding='utf-8') as f:
            f.write(f"SK BLACK Ultimate Report\n")
            f.write(f"Generated: {datetime.now().isoformat()}\n")
            f.write("="*50 + "\n\n")

            if isinstance(data, dict):
                self._write_dict_to_text(data, f)
            else:
                f.write(str(data))

    def save_html_report(self, data, filename):
        """Generate laporan HTML"""
        content_html = self._to_html(data)
        html = f"""
        <html>
        <head>
            <title>SK BLACK Ultimate Report</title>
            <style>
                body {{ font-family: Arial, sans-serif; margin: 20px; background-color: #f9f9f9; }}
                .header {{ background: #1e1e1e; color: #fff; padding: 15px; border-radius: 5px; }}
                .content {{ margin-top: 20px; background: #fff; padding: 15px; border-radius: 5px; box-shadow: 0 0 10px rgba(0,0,0,0.1); }}
                .footer {{ margin-top: 20px; font-size: 0.8em; color: #666; text-align: center; }}
                ul {{ list-style-type: none; padding-left: 15px; }}
                li {{ margin: 5px 0; }}
            </style>
        </head>
        <body>
            <div class="header">
                <h2>SK BLACK Ultimate Report</h2>
                <p>Generated: {datetime.now().isoformat()}</p>
            </div>
            <div class="content">
                {content_html}
            </div>
            <div class="footer">
                <p>Generated by SK BLACK Ultimate Toolkit</p>
            </div>
        </body>
        </html>
        """

        with open(filename, 'w', encoding='utf-8') as f:
            f.write(html)

    def display_result_table(self, data, title="Scan Results"):
        """Tampilkan hasil dalam format Rich Table di terminal"""
        table = Table(title=title, show_header=True, header_style="bold magenta")
        table.add_column("Key", style="cyan", no_wrap=True)
        table.add_column("Value", style="green")

        if isinstance(data, dict):
            for key, value in data.items():
                table.add_row(str(key), str(value))
        else:
            table.add_row("Data", str(data))

        self.console.print(table)

    def _write_dict_to_text(self, data, file, indent=0):
        """Helper untuk menulis dictionary ke text"""
        for key, value in data.items():
            if isinstance(value, dict):
                file.write("    " * indent + f"{key}:\n")
                self._write_dict_to_text(value, file, indent + 1)
            else:
                file.write("    " * indent + f"{key}: {value}\n")

    def _to_html(self, data):
        """Helper untuk convert dictionary/list ke HTML secara aman"""
        if isinstance(data, dict):
            html = "<ul>"
            for key, value in data.items():
                html += f"<li><strong>{key}:</strong> {self._to_html(value)}</li>"
            html += "</ul>"
            return html
        elif isinstance(data, list):
            html = "<ul>"
            for item in data:
                html += f"<li>{self._to_html(item)}</li>"
            html += "</ul>"
            return html
        else:
            return str(data)
